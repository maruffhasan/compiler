OUTDEC:
	PUSH EBX
	PUSH ECX
	PUSH EDX
	PUSH ESI
	OR EAX, EAX
	JGE OUTDEC_POSITIVE
	NEG EAX
	PUSH EAX
	SUB ESP, 4
	MOV byte [ESP], '-'
	MOV EAX, 4
	MOV EBX, 1
	MOV ECX, ESP
	MOV EDX, 1
	INT 0x80
	ADD ESP, 4
	POP EAX
OUTDEC_POSITIVE:
	XOR ECX, ECX
	MOV EBX, 10
OUTDEC_DIGIT_LOOP:
	XOR EDX, EDX
	DIV EBX
	ADD DL, 30h
	PUSH EDX
	INC ECX
	TEST EAX, EAX
	JNZ OUTDEC_DIGIT_LOOP
OUTDEC_PRINT_LOOP:
	TEST ECX, ECX
	JZ OUTDEC_NEWLINE
	PUSH ECX
	MOV EAX, 4
	MOV EBX, 1
	LEA ECX, [ESP+4]
	MOV EDX, 1
	INT 0x80
	POP ECX
	ADD ESP, 4
	DEC ECX
	JMP OUTDEC_PRINT_LOOP
OUTDEC_NEWLINE:
